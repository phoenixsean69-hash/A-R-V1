function deterministicSignedUnit(
  key: string,
): number {
  let hash = 2166136261;

  for (
    let index = 0;
    index < key.length;
    index += 1
  ) {
    hash ^= key.charCodeAt(
      index,
    );
    hash = Math.imul(
      hash,
      16777619,
    );
  }

  return (hash & 1) === 0
    ? 1
    : -1;
}

