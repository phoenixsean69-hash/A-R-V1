function sampleAuthoredParticipant(
  participant:
    ReconstructionVehicle,
  timeSeconds: number,
  widthMetres: number,
  heightMetres: number,
): {
  position:
    ReconstructionPosition;
  rotationDegrees: number;
  speedKmh: number;
  velocityWorld:
    Vector2;
} {
  const points =
    stripPhysicsPoints(
      participant,
    );

  /*
   * [RoadSafe:RapierManualBezierSamplingV1]
   *
   * Keep the existing authored sampler for every normal route. A participant
   * with investigator-controlled Bezier segments is sampled from that same
   * cubic path so Rapier begins from the same visible position/heading.
   */
  if (
    hasManualBezierSegments(
      participant,
    )
  ) {
    const bezierSample =
      sampleManualBezierAtTime(
        {
          ...participant,
          pathPoints:
            points,
        },
        timeSeconds,
        {
          widthMetres,
          heightMetres,
        },
      );

    if (
      bezierSample
    ) {
      const speedKmh =
        participant.physics
          ?.inputSpeedKmh ??
        participant
          .estimatedSpeedKmh;

      const speedMps =
        speedKmh /
        3.6;

      const directionRadians =
        degreesToRadians(
          bezierSample
            .rotationDegrees,
        );

      return {
        position:
          bezierSample.position,

        rotationDegrees:
          bezierSample
            .rotationDegrees,

        speedKmh,

        velocityWorld: {
          x:
            Math.cos(
              directionRadians,
            ) *
            speedMps,

          y:
            Math.sin(
              directionRadians,
            ) *
            speedMps,
        },
      };
    }
  }

  if (
    points.length === 0
  ) {
    const rotation =
      participant
        .startRotation;

    const direction = {
      x:
        Math.cos(
          degreesToRadians(
            rotation,
          ),
        ),

      y:
        Math.sin(
          degreesToRadians(
            rotation,
          ),
        ),
    };

    const speedKmh =
      participant.physics
        ?.inputSpeedKmh ??
      participant
        .estimatedSpeedKmh;

    const speedMps =
      speedKmh /
      3.6;

    return {
      position: {
        ...participant
          .startPosition,
      },
      rotationDegrees:
        rotation,
      speedKmh,
      velocityWorld: {
        x:
          direction.x *
          speedMps,
        y:
          direction.y *
          speedMps,
      },
    };
  }

  if (
    points.length === 1 ||
    timeSeconds <=
      points[0]
        .timeSeconds
  ) {
    const point =
      points[0];

    const next =
      points[1] ??
      point;

    const startWorld =
      scenePositionToWorld(
        point.position,
        widthMetres,
        heightMetres,
      );

    const endWorld =
      scenePositionToWorld(
        next.position,
        widthMetres,
        heightMetres,
      );

    const direction =
      normalise2(
        {
          x:
            endWorld.x -
            startWorld.x,

          y:
            endWorld.y -
            startWorld.y,
        },
        {
          x:
            Math.cos(
              degreesToRadians(
                point.rotation,
              ),
            ),

          y:
            Math.sin(
              degreesToRadians(
                point.rotation,
              ),
            ),
        },
      );

    const speedKmh =
      participant.physics
        ?.inputSpeedKmh ??
      point.speedKmh ??
      participant
        .estimatedSpeedKmh;

    const speedMps =
      speedKmh /
      3.6;

    return {
      position: {
        ...point.position,
      },
      rotationDegrees:
        point.rotation,
      speedKmh,
      velocityWorld: {
        x:
          direction.x *
          speedMps,
        y:
          direction.y *
          speedMps,
      },
    };
  }

  const last =
    points[
      points.length -
      1
    ];

  if (
    timeSeconds >=
    last.timeSeconds
  ) {
    const previous =
      points[
        Math.max(
          0,
          points.length -
            2,
        )
      ];

    const previousWorld =
      scenePositionToWorld(
        previous.position,
        widthMetres,
        heightMetres,
      );

    const lastWorld =
      scenePositionToWorld(
        last.position,
        widthMetres,
        heightMetres,
      );

    const direction =
      normalise2(
        {
          x:
            lastWorld.x -
            previousWorld.x,

          y:
            lastWorld.y -
            previousWorld.y,
        },
        {
          x:
            Math.cos(
              degreesToRadians(
                last.rotation,
              ),
            ),

          y:
            Math.sin(
              degreesToRadians(
                last.rotation,
              ),
            ),
        },
      );

    const speedKmh =
      participant.physics
        ?.inputSpeedKmh ??
      last.speedKmh ??
      participant
        .estimatedSpeedKmh;

    const speedMps =
      speedKmh /
      3.6;

    return {
      position: {
        ...last.position,
      },
      rotationDegrees:
        last.rotation,
      speedKmh,
      velocityWorld: {
        x:
          direction.x *
          speedMps,
        y:
          direction.y *
          speedMps,
      },
    };
  }

  let start =
    points[0];

  let end =
    points[1];

  for (
    let index = 0;
    index <
      points.length -
        1;
    index += 1
  ) {
    const candidateStart =
      points[index];

    const candidateEnd =
      points[index + 1];

    if (
      timeSeconds >=
        candidateStart
          .timeSeconds &&
      timeSeconds <=
        candidateEnd
          .timeSeconds
    ) {
      start =
        candidateStart;

      end =
        candidateEnd;

      break;
    }
  }

  const duration =
    Math.max(
      0.0001,
      end.timeSeconds -
        start.timeSeconds,
    );

  const progress =
    clamp(
      (
        timeSeconds -
        start.timeSeconds
      ) /
        duration,
      0,
      1,
    );

  const position = {
    x:
      interpolate(
        start.position.x,
        end.position.x,
        progress,
      ),

    y:
      interpolate(
        start.position.y,
        end.position.y,
        progress,
      ),
  };

  const startWorld =
    scenePositionToWorld(
      start.position,
      widthMetres,
      heightMetres,
    );

  const endWorld =
    scenePositionToWorld(
      end.position,
      widthMetres,
      heightMetres,
    );

  const direction =
    normalise2(
      {
        x:
          endWorld.x -
          startWorld.x,

        y:
          endWorld.y -
          startWorld.y,
      },
      {
        x:
          Math.cos(
            degreesToRadians(
              start.rotation,
            ),
          ),

        y:
          Math.sin(
            degreesToRadians(
              start.rotation,
            ),
          ),
      },
    );

  const authoredSpeed =
    interpolate(
      start.speedKmh,
      end.speedKmh,
      progress,
    );

  const speedKmh =
    participant.physics
      ?.inputSpeedKmh ??
    authoredSpeed ??
    participant
      .estimatedSpeedKmh;

  const speedMps =
    speedKmh /
    3.6;

  return {
    position,
    rotationDegrees:
      interpolateAngle(
        start.rotation,
        end.rotation,
        progress,
      ),
    speedKmh,
    velocityWorld: {
      x:
        direction.x *
        speedMps,
      y:
        direction.y *
        speedMps,
    },
  };
}

function sampleAuthoredParticipantWithReaction(
  participant:
    ReconstructionVehicle,
  timeSeconds: number,
  widthMetres: number,
  heightMetres: number,
  impactTimeOverrideSeconds?: number,
): {
  position:
    ReconstructionPosition;
  rotationDegrees: number;
  speedKmh: number;
  velocityWorld:
    Vector2;
} {
  const sample =
    sampleAuthoredParticipant(
      participant,
      timeSeconds,
      widthMetres,
      heightMetres,
    );

  const reaction =
    getParticipantAccidentReactionState(
      participant,
      timeSeconds,
      sample.position,
      sample.rotationDegrees,
      sample.speedKmh,
      impactTimeOverrideSeconds,
    );

  const speedMps =
    reaction
      .adjustedSpeedKmh /
    3.6;

  const directionRadians =
    degreesToRadians(
      reaction
        .suggestedHeadingDegrees,
    );

  return {
    position:
      sample.position,
    rotationDegrees:
      reaction
        .suggestedHeadingDegrees,
    speedKmh:
      reaction
        .adjustedSpeedKmh,
    velocityWorld: {
      x:
        Math.cos(
          directionRadians,
        ) *
        speedMps,
      y:
        Math.sin(
          directionRadians,
        ) *
        speedMps,
    },
  };
}

function groundSurfaceFriction(
  surface:
    AccidentReconstruction["scene"]["groundSurface"],
): number {
  switch (
    surface
  ) {
    case "Firm Soil":
      return 0.62;

    case "Loose Soil":
      return 0.42;

    case "Grass":
      return 0.45;

    case "Gravel":
      return 0.5;

    case "Sand":
      return 0.35;

    case "Mud":
      return 0.28;

    case "Concrete":
      return 0.82;

    case "Paved Yard":
      return 0.75;

    case "Mixed Surface":
      return 0.5;

    case "Unclassified Ground":
    default:
      return 0.5;
  }
}

function sceneSurfaceFriction(
  reconstruction:
    AccidentReconstruction,
): number {
  const scene =
    reconstruction.scene;

  const road =
    scene.roadSurface ===
    "Wet"
      ? 0.52
      : scene.roadSurface ===
          "Damaged"
        ? 0.62
        : 0.78;

  const ground =
    groundSurfaceFriction(
      scene.groundSurface,
    );

  let coefficient =
    scene.sceneEnvironment ===
      "Road / Junction"
      ? road
      : scene.sceneEnvironment ===
          "Mixed Site"
        ? (
            road +
            ground
          ) /
          2
        : ground;

  if (
    scene.weather ===
    "Rain"
  ) {
    coefficient *= 0.82;
  }

  if (
    scene.weather ===
    "Dust"
  ) {
    coefficient *= 0.9;
  }

  return coefficient;
}

function participantProfile(
  participant:
    ReconstructionVehicle,
): ParticipantPhysicsProfile {
  return {
    ...getDefaultParticipantPhysics(
      participant,
    ),
    ...(participant.physics ??
      {}),
  };
}

function objectProfile(
  object:
    ReconstructionSceneObject,
): SceneObjectPhysicsProfile {
  const base = {
    ...getDefaultSceneObjectPhysics(
      object,
    ),
    ...(object.physics ??
      {}),
  };

  /*
   * [RoadSafe:RoadHazardInteractionV1]
   *
   * The legacy forensic layer intentionally treated several Road Hazards as
   * non-collidable modifiers. Rapier gives them explicit dynamics semantics:
   * surface hazards become overlap regions and Debris/Fallen Branch become
   * dynamic rigid bodies. Investigator-entered overrides still win.
   */
  if (
    object.type ===
    "Road Crack"
  ) {
    const width = Math.max(
      0.08,
      object.widthMetres ??
        0.18,
    );

    return {
      ...base,
      enabled: true,
      collidable: false,
      collisionShape:
        "Oriented Box",
      collisionRadiusMetres:
        Math.max(
          0.04,
          width / 2,
        ),
      widthMetres: width,
      lengthMetres:
        Math.max(
          0.5,
          object.lengthMetres ??
            2.5,
        ),
      surfaceFrictionMultiplier:
        0.94,
      speedLossFactor:
        0.992,
      deflectionDegrees:
        0.45,
    };
  }

  if (
    ROAD_HAZARD_SURFACE_TYPES.has(
      object.type,
    )
  ) {
    return {
      ...base,
      enabled: true,
      collidable: false,
    };
  }

  if (
    ROAD_HAZARD_DYNAMIC_TYPES.has(
      object.type,
    )
  ) {
    return {
      ...base,
      enabled: true,
      collidable: true,
    };
  }

  return base;
}

function participantContactRestitution(
  participant:
    ReconstructionVehicle,
  profile:
    ParticipantPhysicsProfile,
): number {
  if (
    participant.type ===
      "Car" ||
    participant.type ===
      "Bus" ||
    participant.type ===
      "Truck"
  ) {
    return clamp(
      Math.min(
        profile.restitution,
        0.07,
      ),
      0,
      1,
    );
  }

  if (
    participant.type ===
      "Motorcycle" ||
    participant.type ===
      "Bicycle"
  ) {
    return clamp(
      Math.min(
        profile.restitution,
        0.1,
      ),
      0,
      1,
    );
  }

  return clamp(
    profile.restitution,
    0,
    1,
  );
}

/*
 * [RoadSafe:HumanVisualContactEnvelopeV1]
 *
 * The articulated RoadSafe human is much narrower than the legacy 0.30 m
 * circular envelope. Build the Rapier body from the visible head/shoulder
 * footprint instead.
 *
 * The returned value is the OUTER horizontal radius including the rounded
 * border. It intentionally follows physical dimensions, never visualScale.
 */
function humanVisualContactRadiusMetres(
  participant:
    ReconstructionVehicle,
): number {
  const physical =
    getParticipantPhysicalDimensions(
      participant,
    );

  const headRadius =
    clamp(
      physical
        .heightMetres *
        0.105,
      0.12,
      0.19,
    );

  const shoulderArmEnvelope =
    physical
      .widthMetres *
    0.4;

  return clamp(
    Math.max(
      headRadius,
      shoulderArmEnvelope,
    ),
    0.14,
    0.21,
  );
}

function createParticipantCollider(
  participant:
    ReconstructionVehicle,
  profile:
    ParticipantPhysicsProfile,
) {
  const dimensions =
    participantBodyColliderDimensions(
      participant,
      profile,
    );

  const halfHeight =
    Math.max(
      0.08,
      dimensions
        .heightMetres /
        2,
    );

  if (
    isHumanParticipant(
      participant,
    )
  ) {
    /*
     * Rapier round shapes add borderRadius as outer thickness. Therefore the
     * cylinder core is reduced by the same border so the FINAL collider
     * footprint matches the visible human instead of extending beyond it.
     */
    const borderRadius =
      0.025;

    const outerRadius =
      humanVisualContactRadiusMetres(
        participant,
      );

    return RAPIER
      .ColliderDesc
      .roundCylinder(
        Math.max(
          0.08,
          halfHeight -
            borderRadius,
        ),
        Math.max(
          0.08,
          outerRadius -
            borderRadius,
        ),
        borderRadius,
      );
  }

  const border =
    dimensions
      .borderRadiusMetres;

  return RAPIER
    .ColliderDesc
    .roundCuboid(
      Math.max(
        0.05,
        dimensions
          .lengthMetres /
            2 -
          border,
      ),
      Math.max(
        0.05,
        halfHeight -
          border,
      ),
      Math.max(
        0.05,
        dimensions
          .widthMetres /
            2 -
          border,
      ),
      border,
    );
}

function createSceneObjectCollider(
  object:
    ReconstructionSceneObject,
  profile:
    SceneObjectPhysicsProfile,
  heightMetres: number,
) {
  const length =
    Math.max(
      0.1,
      profile.lengthMetres ??
        object.lengthMetres ??
        profile
          .collisionRadiusMetres *
          2,
    );

  const width =
    Math.max(
      0.1,
      profile.widthMetres ??
        object.widthMetres ??
        profile
          .collisionRadiusMetres *
          2,
    );

  const halfHeight =
    Math.max(
      0.05,
      heightMetres /
        2,
    );

  if (
    profile.collisionShape ===
    "Circle"
  ) {
    return RAPIER
      .ColliderDesc
      .cylinder(
        halfHeight,
        Math.max(
          0.05,
          profile
            .collisionRadiusMetres,
        ),
      );
  }

  return RAPIER
    .ColliderDesc
    .cuboid(
      length / 2,
      halfHeight,
      width / 2,
    );
}

