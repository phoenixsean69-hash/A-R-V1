function distancePointToSegmentMetres(
  point: Vector2,
  start: Vector2,
  end: Vector2,
): number {
  const dx = end.x - start.x;
  const dy = end.y - start.y;
  const lengthSquared =
    dx * dx + dy * dy;

  if (
    lengthSquared <
    0.000001
  ) {
    return Math.hypot(
      point.x - start.x,
      point.y - start.y,
    );
  }

  const progress = clamp(
    (
      (point.x - start.x) * dx +
      (point.y - start.y) * dy
    ) /
      lengthSquared,
    0,
    1,
  );

  return Math.hypot(
    point.x -
      (start.x + dx * progress),
    point.y -
      (start.y + dy * progress),
  );
}

function surfaceZoneContainsPoint(
  zone: SurfaceZoneRuntime,
  point: Vector2,
  widthMetres: number,
  heightMetres: number,
  marginMetres: number,
): boolean {
  const object =
    zone.object;

  if (
    object.type ===
      "Road Crack" &&
    object.tracePoints &&
    object.tracePoints.length >
      1
  ) {
    const trace =
      object.tracePoints.map(
        (position) =>
          scenePositionToWorld(
            position,
            widthMetres,
            heightMetres,
          ),
      );

    const width = Math.max(
      0.06,
      object.widthMetres ??
        zone.profile.widthMetres ??
        0.18,
    );

    for (
      let index = 0;
      index < trace.length - 1;
      index += 1
    ) {
      if (
        distancePointToSegmentMetres(
          point,
          trace[index],
          trace[index + 1],
        ) <=
        width / 2 +
          marginMetres
      ) {
        return true;
      }
    }

    return false;
  }

  const radius = Math.max(
    0.08,
    zone.profile
      .collisionRadiusMetres,
    (
      zone.profile.widthMetres ??
      object.widthMetres ??
      0
    ) /
      2,
  );

  return Math.hypot(
    point.x -
      zone.worldPosition.x,
    point.y -
      zone.worldPosition.y,
  ) <=
    radius +
      marginMetres;
}

function participantSurfaceProbePoints(
  runtime:
    ParticipantRuntime,
): Vector2[] {
  const translation =
    runtime.body.translation();

  const centre = {
    x: translation.x,
    y: translation.z,
  };

  if (
    isHumanParticipant(
      runtime.participant,
    )
  ) {
    return [centre];
  }

  const dimensions =
    participantBodyColliderDimensions(
      runtime.participant,
      runtime.profile,
    );

  const heading =
    degreesToRadians(
      roadSafeRotationFromQuaternion(
        runtime.body.rotation(),
      ),
    );

  const forward = {
    x: Math.cos(heading),
    y: Math.sin(heading),
  };

  const right = {
    x: -forward.y,
    y: forward.x,
  };

  const longitudinal =
    dimensions.lengthMetres *
    0.34;

  const lateral =
    dimensions.widthMetres *
    0.32;

  const points: Vector2[] = [];

  for (
    const longitudinalSign
    of [-1, 1]
  ) {
    for (
      const lateralSign
      of [-1, 1]
    ) {
      points.push({
        x:
          centre.x +
          forward.x *
            longitudinal *
            longitudinalSign +
          right.x *
            lateral *
            lateralSign,
        y:
          centre.y +
          forward.y *
            longitudinal *
            longitudinalSign +
          right.y *
            lateral *
            lateralSign,
      });
    }
  }

  return points;
}

function participantInsideSurfaceZone(
  runtime:
    ParticipantRuntime,
  zone:
    SurfaceZoneRuntime,
  widthMetres: number,
  heightMetres: number,
): boolean {
  const margin =
    isHumanParticipant(
      runtime.participant,
    )
      ? 0.08
      : 0.04;

  return participantSurfaceProbePoints(
    runtime,
  ).some(
    (point) =>
      surfaceZoneContainsPoint(
        zone,
        point,
        widthMetres,
        heightMetres,
        margin,
      ),
  );
}

