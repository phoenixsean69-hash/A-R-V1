export function insertProgressiveRoutePoint({
  pathPoints,
  selectedPointId,
  durationSeconds,
  worldDimensions,
  createId,
}: InsertProgressiveRoutePointOptions): {
  pathPoints: MovementPathPoint[];
  insertedPointId: string;
} {
  const physics = pathPoints
    .filter(
      isPhysicsGeneratedRoutePoint,
    )
    .slice();

  const authored =
    alignAuthoredRouteToTangents(
      pathPoints,
    ).filter(
      (point) =>
        !isPhysicsGeneratedRoutePoint(
          point,
        ),
    );

  if (authored.length < 2) {
    throw new Error(
      "Point 1 and Point Z are required before adding an intermediate point.",
    );
  }

  let segmentIndex =
    selectedPointId
      ? authored.findIndex(
          (point) =>
            point.id ===
            selectedPointId,
        )
      : -1;

  if (
    segmentIndex ===
    authored.length - 1
  ) {
    segmentIndex =
      authored.length - 2;
  }

  if (
    segmentIndex < 0 ||
    segmentIndex >=
      authored.length - 1
  ) {
    let largestDistance = -1;
    segmentIndex = 0;

    for (
      let index = 0;
      index <
      authored.length - 1;
      index += 1
    ) {
      const currentDistance =
        distance(
          authored[index]
            .position,
          authored[index + 1]
            .position,
        );

      if (
        currentDistance >
        largestDistance
      ) {
        largestDistance =
          currentDistance;

        segmentIndex = index;
      }
    }
  }

  const start =
    authored[segmentIndex];

  const end =
    authored[
      segmentIndex + 1
    ];

  const previous =
    authored[
      Math.max(
        0,
        segmentIndex - 1,
      )
    ] ?? start;

  const following =
    authored[
      Math.min(
        authored.length - 1,
        segmentIndex + 2,
      )
    ] ?? end;

  const insertedPointId =
    createId("path-point");

  const inserted:
    MovementPathPoint = {
      id: insertedPointId,
      label: "New route point",
      position:
        catmullRomMidpoint(
          previous.position,
          start.position,
          end.position,
          following.position,
        ),
      timeSeconds: clamp(
        (
          start.timeSeconds +
          end.timeSeconds
        ) / 2,
        0.01,
        Math.max(
          0.01,
          durationSeconds - 0.01,
        ),
      ),
      speedKmh:
        (
          start.speedKmh +
          end.speedKmh
        ) / 2,
      rotation:
        headingDegrees(
          start.position,
          end.position,
          start.rotation,
        ),
      action: "Cruise",
      notes: "",
    };

  const nextAuthored = [
    ...authored.slice(
      0,
      segmentIndex + 1,
    ),
    inserted,
    ...authored.slice(
      segmentIndex + 1,
    ),
  ];

  const aligned =
    alignAuthoredOnlyToTangents(
      redistributeAuthoredTimes(
        relabelPointZRoute(
          nextAuthored,
        ),
        durationSeconds,
        authored[0]
          ?.speedKmh ??
          1,
        worldDimensions,
      ),
    );

  return {
    insertedPointId,
    pathPoints: [
      ...aligned,
      ...physics,
    ].sort(
      (a, b) =>
        a.timeSeconds -
        b.timeSeconds,
    ),
  };
}

export function removeIntermediateRoutePoint({
  pathPoints,
  pointId,
}: {
  pathPoints: MovementPathPoint[];
  pointId: string;
}): MovementPathPoint[] {
  const authored = pathPoints
    .filter(
      (point) =>
        !isPhysicsGeneratedRoutePoint(
          point,
        ),
    )
    .sort(
      (a, b) =>
        a.timeSeconds -
        b.timeSeconds,
    );

  const target =
    authored.find(
      (point) =>
        point.id === pointId,
    );

  if (
    !target ||
    !canDeleteAuthoredRoutePoint(
      target,
      authored,
    )
  ) {
    return pathPoints;
  }

  return alignAuthoredRouteToTangents(
    pathPoints.filter(
      (point) =>
        point.id !== pointId,
    ),
  );
}

export function applySafeAuthoredPointUpdate({
  pathPoints,
  pointId,
  updates,
  collisionPosition,
  durationSeconds,
  speedKmh,
  participantType,
  worldDimensions,
  createId = defaultCreateId,
}: {
  pathPoints: MovementPathPoint[];
  pointId: string;
  updates: Partial<MovementPathPoint>;
  collisionPosition:
    ReconstructionPosition;
  durationSeconds: number;
  speedKmh: number;
  participantType:
    ReconstructionVehicleType;
  worldDimensions?:
    MetricSceneDimensions;
  createId?:
    (prefix: string) => string;
}): MovementPathPoint[] {
  /*
   * Work from the current authored IDs so an editable auto-curve point is not
   * regenerated before the requested drag/update is applied.
   */
  const materialised =
    pathPoints;

  const authored = materialised
    .filter(
      (point) =>
        !isPhysicsGeneratedRoutePoint(
          point,
        ),
    )
    .sort(
      (a, b) =>
        a.timeSeconds -
        b.timeSeconds,
    );

  const target =
    authored.find(
      (point) =>
        point.id === pointId,
    );

  if (!target) {
    return materialised;
  }

  const role =
    getAuthoredRoutePointRole(
      target,
      authored,
    );

  const safeUpdates:
    Partial<MovementPathPoint> = {
      ...updates,
    };

  delete safeUpdates.id;

  if (role === "PointZ") {
    delete safeUpdates.position;
    delete safeUpdates.label;
    delete safeUpdates.action;

    safeUpdates.notes =
      updates.notes
        ? normaliseNotes(
            updates.notes,
            POINT_Z_NOTE_MARKER,
          )
        : target.notes;
  } else if (
    role === "PointOne"
  ) {
    delete safeUpdates.label;

    if (
      updates.action !== undefined &&
      updates.action !== "Start" &&
      updates.action !==
        "Enter Scene"
    ) {
      delete safeUpdates.action;
    }
  } else if (
    updates.action === "Impact"
  ) {
    safeUpdates.action =
      "Cruise";
  }

  if (
    role === "Intermediate" &&
    (
      updates.position !==
        undefined ||
      updates.rotation !==
        undefined
    )
  ) {
    const cleanedNotes = (
      updates.notes ??
      target.notes ??
      ""
    )
      .replace(
        AUTO_ROAD_CURVE_NOTE_MARKER,
        "",
      )
      .replace(
        FREEHAND_ROUTE_NOTE_MARKER,
        "",
      )
      .trim();

    safeUpdates.notes =
      addNoteMarker(
        cleanedNotes,
        MANUAL_ROUTE_ANCHOR_NOTE_MARKER,
      );
  }

  const updated =
    materialised.map(
      (point) =>
        point.id === pointId
          ? {
              ...point,
              ...safeUpdates,
            }
          : point,
    );

  return normalisePointZRoute({
    pathPoints: updated,
    collisionPosition,
    durationSeconds,
    speedKmh,
    participantType,
    worldDimensions,
    createId,
  });
}

