function degreesToRadians(
  degrees: number,
): number {
  return (
    degrees *
    Math.PI /
    180
  );
}

function radiansToDegrees(
  radians: number,
): number {
  return (
    radians *
    180 /
    Math.PI
  );
}

function normaliseDegrees(
  degrees: number,
): number {
  return (
    (degrees % 360) +
    360
  ) % 360;
}

function interpolate(
  start: number,
  end: number,
  progress: number,
): number {
  return (
    start +
    (end - start) *
      progress
  );
}

function interpolateAngle(
  start: number,
  end: number,
  progress: number,
): number {
  const difference =
    (
      (
        end -
        start +
        540
      ) %
        360
    ) -
    180;

  return (
    start +
    difference *
      progress
  );
}

function magnitude2(
  vector: Vector2,
): number {
  return Math.hypot(
    vector.x,
    vector.y,
  );
}

function normalise2(
  vector: Vector2,
  fallback: Vector2 = {
    x: 1,
    y: 0,
  },
): Vector2 {
  const length =
    magnitude2(vector);

  if (
    length <
    0.000001
  ) {
    const fallbackLength =
      magnitude2(fallback) ||
      1;

    return {
      x:
        fallback.x /
        fallbackLength,
      y:
        fallback.y /
        fallbackLength,
    };
  }

  return {
    x:
      vector.x /
      length,
    y:
      vector.y /
      length,
  };
}

