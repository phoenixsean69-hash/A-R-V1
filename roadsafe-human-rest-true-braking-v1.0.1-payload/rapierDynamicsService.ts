function yawQuaternionFromRoadSafeRotation(
  rotationDegrees: number,
): QuaternionLike {
  /*
   * RoadSafe's canonical 2D positive angle rotates +X toward +sceneY.
   * Rapier/Three use a right-handed X/Z plane, so the Y-axis yaw sign is
   * inverted when sceneY is projected onto +Z.
   */
  const yaw =
    -degreesToRadians(
      rotationDegrees,
    );

  const half =
    yaw / 2;

  return {
    x: 0,
    y: Math.sin(half),
    z: 0,
    w: Math.cos(half),
  };
}

function roadSafeRotationFromQuaternion(
  rotation:
    QuaternionLike,
): number {
  const yaw =
    Math.atan2(
      2 *
        (
          rotation.w *
            rotation.y +
          rotation.x *
            rotation.z
        ),
      1 -
        2 *
          (
            rotation.y *
              rotation.y +
            rotation.z *
              rotation.z
          ),
    );

  return normaliseDegrees(
    -radiansToDegrees(
      yaw,
    ),
  );
}

