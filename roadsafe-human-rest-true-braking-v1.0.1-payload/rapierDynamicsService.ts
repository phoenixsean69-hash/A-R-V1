function participantBodyColliderDimensions(
  participant:
    ReconstructionVehicle,
  profile:
    ParticipantPhysicsProfile,
): ParticipantBodyColliderDimensions {
  const asset =
    getParticipantAssetDefinition(
      participant,
    );

  const physical =
    getParticipantPhysicalDimensions(
      participant,
    );

  const defaults =
    getDefaultParticipantPhysics(
      participant,
    );

  const hasCustomLength =
    participant.physics
      ?.lengthMetres !==
      undefined &&
    Math.abs(
      participant.physics
        .lengthMetres -
        (
          defaults
            .lengthMetres ??
          participant.physics
            .lengthMetres
        ),
    ) >
      0.001;

  const hasCustomWidth =
    participant.physics
      ?.widthMetres !==
      undefined &&
    Math.abs(
      participant.physics
        .widthMetres -
        (
          defaults
            .widthMetres ??
          participant.physics
            .widthMetres
        ),
    ) >
      0.001;

  const length =
    Math.max(
      0.2,
      hasCustomLength
        ? (
            profile
              .lengthMetres ??
            physical
              .lengthMetres
          )
        : asset
            .collision
            .lengthMetres,
    );

  const width =
    Math.max(
      0.2,
      hasCustomWidth
        ? (
            profile
              .widthMetres ??
            physical
              .widthMetres
          )
        : asset
            .collision
            .widthMetres,
    );

  const height =
    isHumanParticipant(
      participant,
    )
      ? Math.max(
          0.4,
          physical
            .heightMetres,
        )
      : Math.max(
          0.3,
          physical
            .heightMetres *
            0.72,
        );

  const borderRadius =
    clamp(
      Math.min(
        length *
          0.055,
        width *
          0.12,
        height *
          0.16,
      ),
      0.04,
      0.2,
    );

  return {
    lengthMetres:
      length,
    widthMetres:
      width,
    heightMetres:
      height,
    borderRadiusMetres:
      borderRadius,
  };
}

