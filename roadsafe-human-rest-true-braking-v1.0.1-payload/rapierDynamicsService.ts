/*
 * [RoadSafe:RapierDynamicsV1]
 *
 * Rapier is the rigid-body dynamics layer.
 * RoadSafe Physics V2 remains the forensic calculation/audit layer.
 *
 * The canonical reconstruction stays 2D (scene x/y percentages). Rapier runs
 * a metre-based 3D world using x/z as the road plane and y as vertical.
 * Hidden Rapier trajectory samples are projected back into the same canonical
 * 2D path format, so 2D, 3D, Timeline, AR and reports continue sharing state.
 */

